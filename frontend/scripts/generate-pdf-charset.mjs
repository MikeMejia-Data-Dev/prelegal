// Regenerates src/lib/nda/export/pdfCharset.ts from the bundled PDF font, so the
// app can warn about characters the PDF cannot render. Run after changing fonts:
//   node scripts/generate-pdf-charset.mjs
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const fontkit = createRequire(import.meta.url)("fontkit");
const dir = new URL("../src/lib/nda/export/", import.meta.url);

const sets = ["NotoSans-Regular.ttf", "NotoSans-Bold.ttf"].map(
  (f) => new Set(fontkit.openSync(new URL(`fonts/${f}`, dir).pathname).characterSet),
);
// Only characters present in both weights are safe.
const points = [...sets[0]].filter((cp) => sets.every((s) => s.has(cp))).sort((a, b) => a - b);

const ranges = [];
for (const cp of points) {
  const last = ranges.at(-1);
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}

const body = ranges.map(([a, b]) => (a === b ? `${a}` : `${a},${b}`)).join(";");
writeFileSync(
  new URL("pdfCharset.ts", dir),
  `// Generated by scripts/generate-pdf-charset.mjs from fonts/NotoSans-*.ttf. Do not edit.\n` +
    `// Code point ranges ("start,end" or single) covered by the PDF font.\n` +
    `export const PDF_CHARSET_RANGES = ${JSON.stringify(body)};\n`,
);
console.log(`${points.length} code points in ${ranges.length} ranges`);
